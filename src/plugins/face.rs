//! Face plugins: the host for bundles that extend the face's own
//! surfaces (the face-plugin-host plan). A plugin is a directory in
//! `<FLEET_HOME>/plugins/<name>/` — a `manifest.json` and a static
//! asset — plus a registry state in `<FLEET_HOME>/plugins.json`, so
//! the lifecycle is config, not code.
//!
//! Two tiers, the owner's ruling: **privileged** plugins the owner
//! creates or vouches for (first-class rail entries with the face's
//! own API reach), and **untrusted** plugins creator mode generates
//! (sandboxed to the manifest's declared read-only queries, enforced
//! bridge-side — never trusted, never self-elevating).

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// The registry's file name, beside `routing.json` in the home.
pub const REGISTRY_FILE: &str = "plugins.json";

/// The read-only query names an untrusted plugin may declare. Each
/// names a GET route the bridge already serves read-only; the eval
/// suite drives them, and the bridge enforces the manifest's set.
pub const READ_ONLY_QUERIES: [&str; 12] = [
    "state",
    "home",
    "router",
    "delegation",
    "memory",
    "skills",
    "sessions",
    "usage",
    "workspace-history",
    "tree",
    "related",
    "preview",
];

/// The trust tier, the owner's two kinds.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum FaceTier {
    /// The owner created or vouches for the bundle: a first-class rail
    /// entry with the face's own API reach.
    Privileged,
    /// Generated by creator mode: sandboxed to the manifest's declared
    /// read-only queries, never trusted, never self-elevating.
    Untrusted,
}

/// Where a plugin mounts in the rail.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FaceEntry {
    /// The rail group: `work`, `intelligence`, `knowledge`, or
    /// `system` — the face's own four.
    pub group: String,
    /// The entry's label, in the owner's words.
    pub label: String,
    /// The entry's id; defaults to the plugin's name.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub id: Option<String>,
}

/// One face plugin's manifest.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FaceManifest {
    /// The plugin's name — its directory under `plugins/`, and its
    /// rail entry's id when the entry names none. No path separators:
    /// the name is a directory, never a path.
    pub name: String,
    pub tier: FaceTier,
    pub version: String,
    pub entry: FaceEntry,
    /// The read-only queries an untrusted plugin may ask the bridge
    /// for, by name. Ignored for privileged plugins (their reach is
    /// the face's own), validated against [`READ_ONLY_QUERIES`].
    #[serde(default)]
    pub queries: Vec<String>,
    /// Who or what made it — a path the owner installed from, or
    /// `creator:<session id>` for a generated draft.
    pub provenance: String,
}

impl FaceManifest {
    /// The manifest's path inside a plugin directory.
    pub fn path(plugin_dir: &Path) -> PathBuf {
        plugin_dir.join("manifest.json")
    }

    /// Parse and validate a manifest's bytes: the schema, the name
    /// rules, and — for an untrusted tier — the declared queries
    /// resolving to known read-only routes. Every refusal names the
    /// field (the plan's C0).
    pub fn parse(text: &str) -> Result<FaceManifest, String> {
        let manifest: FaceManifest = serde_json::from_str(text)
            .map_err(|error| format!("the manifest is not a face plugin manifest: {error}"))?;
        if manifest.name.is_empty() {
            return Err("the manifest names no plugin name".to_string());
        }
        if manifest
            .name
            .chars()
            .any(|character| character == '/' || character == '\\' || character == '.')
        {
            return Err(format!(
                "the plugin name `{}` carries a path character — a name is a directory, never a path",
                manifest.name
            ));
        }
        if !matches!(
            manifest.entry.group.as_str(),
            "work" | "intelligence" | "knowledge" | "system"
        ) {
            return Err(format!(
                "the entry's group `{}` is not one of work, intelligence, knowledge, system",
                manifest.entry.group
            ));
        }
        if manifest.entry.label.trim().is_empty() {
            return Err("the entry names no label".to_string());
        }
        if manifest.tier == FaceTier::Untrusted {
            for query in &manifest.queries {
                if !READ_ONLY_QUERIES.contains(&query.as_str()) {
                    return Err(format!(
                        "the untrusted plugin declares `{query}`, which is not a known read-only \
                         query — the sandbox's data arrives only through the declared set"
                    ));
                }
            }
        }
        Ok(manifest)
    }
}

/// One promotion's record: the event, the evaluation verdict it stood
/// on, and when. The registry carries them beside the provenance, so
/// a plugin's reach is always answerable from its history (C9).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FacePromotion {
    pub event: String,
    pub verdict: String,
    pub at: String,
}

/// One plugin's registry state.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FaceState {
    /// Installed plugins mount; disabled ones keep their bundle and
    /// their registry entry and mount nothing.
    pub enabled: bool,
    #[serde(default)]
    pub promotions: Vec<FacePromotion>,
}

/// The registry: plugin name → state.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct FaceRegistry {
    #[serde(default)]
    pub plugins: BTreeMap<String, FaceState>,
}

/// The registry's path in the home.
pub fn registry_path(home: &Path) -> PathBuf {
    home.join(REGISTRY_FILE)
}

/// Read the registry; a missing file is the empty registry, and a
/// malformed one is refused by name (the roster's own discipline).
pub fn load_registry(home: &Path) -> Result<FaceRegistry, String> {
    let path = registry_path(home);
    let Ok(text) = std::fs::read_to_string(&path) else {
        return Ok(FaceRegistry::default());
    };
    serde_json::from_str(&text)
        .map_err(|error| format!("{} is not a plugin registry: {error}", path.display()))
}

/// Write the registry through the settings writer's atomic seam.
pub fn save_registry(home: &Path, registry: &FaceRegistry) -> Result<(), String> {
    let text = serde_json::to_string_pretty(registry)
        .map_err(|error| format!("the registry does not serialize: {error}"))?;
    crate::settings::write_atomic(&registry_path(home), &text)
}

/// A plugin's directory in the home.
pub fn plugin_dir(home: &Path, name: &str) -> PathBuf {
    home.join("plugins").join(name)
}

/// Install a bundle from a path: the directory is copied into the
/// home's `plugins/`, the manifest validated, and the registry gains
/// the plugin enabled. A name collision, a missing manifest, and a
/// failing validation are each refused by name (C0/C1).
pub fn install(home: &Path, from: &Path, tier: Option<FaceTier>) -> Result<String, String> {
    let manifest_path = FaceManifest::path(from);
    let text = std::fs::read_to_string(&manifest_path)
        .map_err(|error| format!("{} cannot be read: {error}", manifest_path.display()))?;
    let mut manifest = FaceManifest::parse(&text)?;
    // The install's tier is the owner's act: an explicit `--privileged`
    // elevates a bundle the manifest declared untrusted, and nothing
    // else moves a tier.
    if let Some(tier) = tier {
        manifest.tier = tier;
    }
    let name = manifest.name.clone();
    let target = plugin_dir(home, &name);
    if target.exists() {
        return Err(format!(
            "`{name}` is already installed — remove it first, or install under another name"
        ));
    }
    copy_dir(from, &target)?;
    // The elevation is persisted: the installed manifest carries the
    // tier the install act chose, so the listing and the sandbox read
    // the bundle as installed, not as first drafted.
    std::fs::write(
        FaceManifest::path(&target),
        serde_json::to_string_pretty(&manifest)
            .map_err(|error| format!("the manifest does not serialize: {error}"))?,
    )
    .map_err(|error| format!("the installed manifest cannot be written: {error}"))?;
    let mut registry = load_registry(home)?;
    registry.plugins.insert(
        name.clone(),
        FaceState {
            enabled: true,
            promotions: Vec::new(),
        },
    );
    save_registry(home, &registry)?;
    Ok(name)
}

/// Copy one directory's whole tree — the bundle's asset files ride
/// with the manifest.
fn copy_dir(from: &Path, to: &Path) -> Result<(), String> {
    std::fs::create_dir_all(to)
        .map_err(|error| format!("{} cannot be created: {error}", to.display()))?;
    for entry in std::fs::read_dir(from)
        .map_err(|error| format!("{} cannot be read: {error}", from.display()))?
    {
        let entry = entry.map_err(|error| error.to_string())?;
        let target = to.join(entry.file_name());
        if entry.path().is_dir() {
            copy_dir(&entry.path(), &target)?;
        } else {
            std::fs::copy(entry.path(), &target)
                .map_err(|error| format!("{} cannot be copied: {error}", entry.path().display()))?;
        }
    }
    Ok(())
}

/// Enable or disable an installed plugin — the registry flips, the
/// bundle stays (C1).
pub fn set_enabled(home: &Path, name: &str, enabled: bool) -> Result<(), String> {
    let mut registry = load_registry(home)?;
    let state = registry.plugins.get_mut(name).ok_or_else(|| {
        format!(
            "`{name}` is not installed — nothing to {}",
            if enabled { "enable" } else { "disable" }
        )
    })?;
    state.enabled = enabled;
    save_registry(home, &registry)
}

/// Remove an installed plugin: the registry entry and the bundle
/// directory both go. The blast radius is the surface's to name —
/// the caller renders what the plugin's reach was (C1).
pub fn remove(home: &Path, name: &str) -> Result<(), String> {
    let mut registry = load_registry(home)?;
    let state = registry
        .plugins
        .remove(name)
        .ok_or_else(|| format!("`{name}` is not installed — nothing to remove"))?;
    let _ = state;
    save_registry(home, &registry)?;
    let dir = plugin_dir(home, name);
    if dir.exists() {
        std::fs::remove_dir_all(&dir)
            .map_err(|error| format!("{} cannot be removed: {error}", dir.display()))?;
    }
    Ok(())
}

/// One listing row: what the `fleet plugins` card renders.
pub struct FaceListing {
    pub name: String,
    pub tier: FaceTier,
    pub enabled: bool,
    pub group: String,
    pub label: String,
    pub version: String,
    pub provenance: String,
    pub promotions: Vec<FacePromotion>,
}

/// List the installed plugins, in registry order, each with its
/// manifest read fresh from the bundle (a bundle edited after install
/// is the bundle the listing shows).
pub fn list(home: &Path) -> Result<Vec<FaceListing>, String> {
    let registry = load_registry(home)?;
    let mut listings = Vec::new();
    for (name, state) in &registry.plugins {
        let manifest_path = FaceManifest::path(&plugin_dir(home, name));
        let manifest = std::fs::read_to_string(&manifest_path)
            .ok()
            .and_then(|text| FaceManifest::parse(&text).ok());
        let Some(manifest) = manifest else {
            listings.push(FaceListing {
                name: name.clone(),
                tier: FaceTier::Untrusted,
                enabled: false,
                group: String::new(),
                label: String::new(),
                version: String::new(),
                provenance: String::new(),
                promotions: state.promotions.clone(),
            });
            continue;
        };
        listings.push(FaceListing {
            name: name.clone(),
            tier: manifest.tier,
            enabled: state.enabled,
            group: manifest.entry.group,
            label: manifest.entry.label,
            version: manifest.version,
            provenance: manifest.provenance,
            promotions: state.promotions.clone(),
        });
    }
    Ok(listings)
}

/// Record a promotion on a plugin's registry state (the ladder's
/// gated step, C9).
pub fn record_promotion(home: &Path, name: &str, event: &str, verdict: &str) -> Result<(), String> {
    let mut registry = load_registry(home)?;
    let state = registry
        .plugins
        .get_mut(name)
        .ok_or_else(|| format!("`{name}` is not installed — nothing to promote"))?;
    state.promotions.push(FacePromotion {
        event: event.to_string(),
        verdict: verdict.to_string(),
        at: crate::session::iso_utc_stamp(std::time::SystemTime::now()).unwrap_or_default(),
    });
    save_registry(home, &registry)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(tag: &str) -> PathBuf {
        let home = std::env::temp_dir().join(format!("fleet-plugins-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&home);
        std::fs::create_dir_all(&home).unwrap();
        home
    }

    fn bundle(tag: &str, manifest: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "fleet-bundle-{tag}-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_nanos())
                .unwrap_or(0)
        ));
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(FaceManifest::path(&dir), manifest).unwrap();
        std::fs::write(dir.join("index.html"), "<html>the plugin</html>").unwrap();
        dir
    }

    const MANIFEST: &str = r#"{
        "name": "stats",
        "tier": "untrusted",
        "version": "0.1.0",
        "entry": { "group": "work", "label": "conversation statistics" },
        "queries": ["state", "sessions"],
        "provenance": "creator:conv-9"
    }"#;

    #[test]
    fn a_bundle_installs_and_the_registry_rides_the_writer() {
        let home = scratch("install");
        let name = install(&home, &bundle("ok", MANIFEST), None).expect("installs");
        assert_eq!(name, "stats");
        // The bundle copied whole, and the registry parsed back.
        assert!(plugin_dir(&home, "stats").join("index.html").exists());
        let registry = load_registry(&home).expect("the registry reads");
        let state = registry.plugins.get("stats").expect("the state");
        assert!(state.enabled);
        let listings = list(&home).expect("lists");
        assert_eq!(listings.len(), 1);
        assert_eq!(listings[0].tier, FaceTier::Untrusted);
        assert_eq!(listings[0].group, "work");
        assert_eq!(listings[0].label, "conversation statistics");
        assert_eq!(listings[0].provenance, "creator:conv-9");
        let _ = std::fs::remove_dir_all(&home);
    }

    #[test]
    fn the_refusals_name_the_field() {
        // A colliding name.
        let home = scratch("refusals");
        let dir = bundle("collide", MANIFEST);
        install(&home, &dir, None).expect("the first installs");
        let error = install(&home, &dir, None).expect_err("the second refuses");
        assert!(error.contains("already installed"), "{error}");
        // A tier-less manifest.
        let no_tier = r#"{"name": "x", "version": "0.1.0", "entry": {"group": "work", "label": "x"}, "provenance": "p"}"#;
        let error = install(&home, &bundle("notier", no_tier), None).expect_err("refuses");
        assert!(error.contains("manifest"), "{error}");
        // An unknown tier.
        let bad_tier = MANIFEST.replace("\"untrusted\"", "\"xmpp\"");
        let error = install(&home, &bundle("badtier", &bad_tier), None).expect_err("refuses");
        assert!(
            error.contains("tier") || error.contains("manifest"),
            "{error}"
        );
        // A path-y name.
        let pathy = MANIFEST.replace("\"stats\"", "\"../escape\"");
        let error = FaceManifest::parse(&pathy).expect_err("refuses");
        assert!(error.contains("path character"), "{error}");
        // An untrusted manifest declaring a non-read-only query.
        let bad_query = MANIFEST.replace("\"state\"", "\"settings\"");
        let error = install(&home, &bundle("badquery", &bad_query), None).expect_err("refuses");
        assert!(
            error.contains("settings") && error.contains("read-only"),
            "{error}"
        );
        let _ = std::fs::remove_dir_all(&home);
    }

    #[test]
    fn enable_disable_and_remove_move_the_state() {
        let home = scratch("lifecycle");
        install(&home, &bundle("life", MANIFEST), None).expect("installs");
        set_enabled(&home, "stats", false).expect("disables");
        let listings = list(&home).expect("lists");
        assert!(!listings[0].enabled, "a disabled plugin mounts nothing");
        set_enabled(&home, "stats", true).expect("enables");
        assert!(list(&home).unwrap()[0].enabled);
        // The bundle stays through the toggle.
        assert!(plugin_dir(&home, "stats").exists());
        remove(&home, "stats").expect("removes");
        assert!(
            !plugin_dir(&home, "stats").exists(),
            "remove deletes the bundle"
        );
        assert!(list(&home).unwrap().is_empty());
        let error = remove(&home, "stats").expect_err("the second remove refuses");
        assert!(error.contains("not installed"), "{error}");
        let _ = std::fs::remove_dir_all(&home);
    }

    #[tokio::test]
    async fn the_declared_query_set_is_the_sandboxes_whole_data_path() {
        // The C3 enforcement lives bridge-side, but the manifest's own
        // validation is the first gate: an untrusted manifest's queries
        // resolve to known read-only routes, and the set is what the
        // bridge enforces.
        let manifest = FaceManifest::parse(MANIFEST).expect("parses");
        assert_eq!(manifest.queries, vec!["state", "sessions"]);
        for query in &manifest.queries {
            assert!(READ_ONLY_QUERIES.contains(&query.as_str()), "{query}");
        }
        let bad = MANIFEST.replace("\"state\"", "\"settings\"");
        let error = FaceManifest::parse(&bad).expect_err("refuses");
        assert!(error.contains("settings") && error.contains("read-only"), "{error}");
    }

    #[test]
    fn the_privileged_install_is_the_elevation_act() {
        let home = scratch("privileged");
        let name = install(&home, &bundle("priv", MANIFEST), Some(FaceTier::Privileged))
            .expect("installs");
        assert_eq!(name, "stats");
        let listings = list(&home).expect("lists");
        assert_eq!(listings[0].tier, FaceTier::Privileged);
        let _ = std::fs::remove_dir_all(&home);
    }
}
